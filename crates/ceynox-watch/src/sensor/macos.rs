//! The macOS sensor, built on the sandbox that ships with the system.
//!
//! The command runs under `sandbox-exec` with a profile that allows
//! everything and asks for a report of what matters: programs started,
//! processes forked, catalog files read, files written, connections made.
//! The kernel writes those reports to the system log, where `log stream`
//! reads them back. Nothing is installed, nothing runs as root, and no
//! entitlement or system extension is involved.
//!
//! What this cannot do, and the Linux sensor can:
//!
//! - attach to processes that are already running;
//! - watch a program that puts itself in a sandbox, because macOS does not
//!   allow a sandbox inside a sandbox;
//! - see the address of a connection. The report carries only the port.
//! - see a process end.
//!
//! Reports are told apart from everyone else's by a tag unique to this run,
//! which the profile attaches to every report it asks for.

use std::collections::{HashMap, VecDeque};

use crate::{
    classify,
    event::{Event, Peer, What},
};

/// Said when we find ourselves inside a sandbox already.
#[cfg(target_os = "macos")]
pub const NESTED: &str = "ceynox-watch cannot run inside another sandbox on macOS, and this shell is in one \
     (some terminals, editors and AI agents sandbox the commands they run)";

/// Build the sandbox profile. `all_reads` reports every file read instead
/// of only those in catalog locations (verbose mode).
pub fn profile(tag: &str, home: &str, all_reads: bool) -> String {
    // The tag is generated by us from hex digits; this keeps it that way.
    let tag: String = tag.chars().filter(char::is_ascii_alphanumeric).collect();
    let report = format!("(with report) (with message \"{tag}\")");
    let mut p = String::from("(version 1)\n(allow default)\n");
    p.push_str(&format!("(allow process-exec* {report})\n"));
    p.push_str(&format!("(allow process-fork {report})\n"));
    p.push_str(&format!("(allow network-outbound {report})\n"));
    // Terminals and /dev/null are written to constantly and say nothing.
    p.push_str(&format!("(allow file-write* (require-not (subpath \"/dev\")) {report})\n"));
    if all_reads {
        p.push_str(&format!("(allow file-read-data (require-not (subpath \"/dev\")) {report})\n"));
    } else {
        p.push_str("(allow file-read-data\n  (regex");
        for pattern in classify::read_patterns(home) {
            // Inside #"..." a quote would end the expression. The patterns
            // never contain one (tested); drop any that somehow does.
            if !pattern.contains('"') {
                p.push_str(&format!("\n    #\"{pattern}\""));
            }
        }
        p.push_str(&format!(")\n  {report})\n"));
    }
    p
}

/// One sandbox report, as far as we use it.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Report {
    /// Name of the process at the time (before an exec, the old name).
    pub comm: String,
    pub pid: u32,
    pub op: Op,
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub enum Op {
    Exec { path: String },
    Fork,
    Read { path: String },
    Write { path: String },
    Unix { path: String },
    Port { port: u16 },
}

/// Parse the message of a sandbox report:
/// `Sandbox: cat(52486) allow file-read-data /Users/sam/.aws/credentials`
/// followed by a line with the tag. `None` for anything else, including
/// denials and the kernel's "N duplicate reports for ..." notices.
pub fn parse_report(message: &str) -> Option<Report> {
    let line = message.lines().next()?.strip_prefix("Sandbox: ")?;
    // The process name may itself contain parentheses and spaces, so find
    // the end of "(pid) allow " rather than the first parenthesis.
    let (who, what) = line.split_once(") allow ")?;
    let (comm, pid) = who.rsplit_once('(')?;
    let pid: u32 = pid.parse().ok()?;
    let (op, rest) = what.split_once(' ').unwrap_or((what, ""));
    let op = match op {
        "process-fork" => Op::Fork,
        "process-exec*" | "process-exec" | "process-exec-interpreter" => Op::Exec { path: normalize(rest)? },
        "file-read-data" => Op::Read { path: normalize(rest)? },
        o if o.starts_with("file-write") => Op::Write { path: normalize(rest)? },
        "network-outbound" => match rest.strip_prefix("remote:") {
            Some(remote) => Op::Port { port: remote.rsplit_once(':')?.1.parse().ok()? },
            None => Op::Unix { path: normalize(rest)? },
        },
        _ => return None,
    };
    Some(Report { comm: comm.to_string(), pid, op })
}

/// Milliseconds since the Unix epoch for a system-log timestamp such as
/// `2026-11-18 20:06:01.074352+0530`. Reports are stamped by the kernel when
/// the thing happened; we read them a moment later, and the difference
/// would put events out of order against the packet capture's own times.
pub fn log_time(stamp: &str) -> Option<u64> {
    let (date, rest) = stamp.split_once(' ')?;
    let mut ymd = date.splitn(3, '-').map(|p| p.parse::<i64>().ok());
    let (year, month, day) = (ymd.next()??, ymd.next()??, ymd.next()??);
    // The zone is the last five characters: a sign and HHMM.
    let (time, zone) = rest.split_at_checked(rest.len().checked_sub(5)?)?;
    let sign = match zone.as_bytes().first()? {
        b'+' => 1,
        b'-' => -1,
        _ => return None,
    };
    let offset_min = zone.get(1..3)?.parse::<i64>().ok()? * 60 + zone.get(3..5)?.parse::<i64>().ok()?;
    let (clock, fraction) = time.split_once('.').unwrap_or((time, "0"));
    let mut hms = clock.splitn(3, ':').map(|p| p.parse::<i64>().ok());
    let (hour, minute, second) = (hms.next()??, hms.next()??, hms.next()??);
    if !(1..=12).contains(&month) || !(1..=31).contains(&day) || hour > 23 || minute > 59 || second > 60 {
        return None;
    }
    let millis = format!("{fraction:0<3}").get(..3)?.parse::<i64>().ok()?;

    // Days from 1970-01-01 to the date, proleptic Gregorian calendar.
    let y = if month <= 2 { year - 1 } else { year };
    let era = y.div_euclid(400);
    let year_of_era = y.rem_euclid(400);
    let day_of_year = (153 * (month + if month > 2 { -3 } else { 9 }) + 2) / 5 + day - 1;
    let day_of_era = year_of_era * 365 + year_of_era / 4 - year_of_era / 100 + day_of_year;
    let days = era * 146_097 + day_of_era - 719_468;

    let seconds = days * 86_400 + hour * 3600 + minute * 60 + second - sign * offset_min * 60;
    u64::try_from(seconds * 1000 + millis).ok()
}

/// macOS keeps /etc, /var and /tmp under /private and reports them that
/// way. Show them the way people write them.
pub fn normalize(path: &str) -> Option<String> {
    if !path.starts_with('/') {
        return None;
    }
    for alias in ["/etc", "/var", "/tmp"] {
        if let Some(rest) = path.strip_prefix("/private")
            && rest.starts_with(alias)
            && matches!(rest.as_bytes().get(alias.len()), None | Some(b'/'))
        {
            return Some(rest.to_string());
        }
    }
    Some(path.to_string())
}

/// What a look at the process table says about a process.
#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct ProcInfo {
    pub ppid: u32,
    /// The program it is running right now: its path, or just the name
    /// the kernel keeps for it. Only the name is compared.
    pub exe: String,
    pub args: Vec<String>,
    pub cwd: Option<String>,
}

/// Questions the tracker asks about live processes and files. A trait so
/// the tests can answer them from a script.
pub trait Table: Send {
    fn info(&mut self, pid: u32) -> Option<ProcInfo>;
    /// Pids of the processes whose parent is `pid`.
    fn children(&mut self, pid: u32) -> Vec<u32>;
    /// Does the file start with `#!`?
    fn is_script(&mut self, path: &str) -> bool;
    /// The file a path leads to once symlinks are followed.
    fn resolve(&mut self, path: &str) -> String;
    fn is_dir(&mut self, path: &str) -> bool;
}

/// A child whose pid is not known yet.
#[derive(Debug)]
struct Expected {
    parent: u32,
    /// The name its first report will carry.
    comm: String,
    /// For a spawned child, the program it was started with.
    spawned: Option<String>,
}

/// Turns the stream of reports into events, reconstructing which process
/// started which. The reports do not say so directly:
///
/// - A fork report names the parent but not the child. The child shows up
///   in a later report under a new pid, still carrying the parent's name.
/// - `posix_spawn`, which most modern programs use instead of fork and
///   exec, produces a single exec report under the *parent's* pid. It looks
///   exactly like the parent replacing itself with the new program.
///
/// The process table settles what it can while the processes are still
/// there to ask about; order and names settle the rest.
pub struct Tracker {
    uid: u32,
    /// Program each known process is running, by file name.
    running: HashMap<u32, String>,
    expected: VecDeque<Expected>,
    table: Box<dyn Table>,
    /// The command line we started, for the first program reported: its
    /// arguments are known exactly and need no lookup.
    first: Option<Vec<String>>,
    /// Stand-in pids for children that came and went unseen.
    next_unseen: u32,
}

impl std::fmt::Debug for Tracker {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.debug_struct("Tracker").field("known", &self.running.len()).finish_non_exhaustive()
    }
}

/// Unclaimed children kept. More than this means children that never did
/// anything reportable; the oldest are forgotten.
const MAX_EXPECTED: usize = 4096;
/// The kernel keeps 15 characters of a process name.
const COMM_LEN: usize = 15;

fn base(path: &str) -> &str {
    path.rsplit('/').next().unwrap_or(path)
}

fn comm_of(path: &str) -> String {
    base(path).chars().take(COMM_LEN).collect()
}

/// Do two paths or names refer to the same program, as far as the kernel's
/// shortened process names can tell?
fn same_program(a: &str, b: &str) -> bool {
    comm_of(a) == comm_of(b)
}

impl Tracker {
    pub fn new(uid: u32, table: Box<dyn Table>) -> Self {
        Self {
            uid,
            running: HashMap::new(),
            expected: VecDeque::new(),
            table,
            first: None,
            // Far above any real pid (macOS pids stay below 100,000).
            next_unseen: 4_000_000_000,
        }
    }

    /// Give the command line of the first program that will be reported.
    pub fn starting_with(mut self, command: Vec<String>) -> Self {
        self.first = Some(command);
        self
    }

    fn expect(&mut self, child: Expected) {
        if self.expected.len() >= MAX_EXPECTED {
            self.expected.pop_front();
        }
        self.expected.push_back(child);
    }

    /// Take the oldest expected child that fits a pid seen for the first
    /// time: one of `parent` if the parent is known for certain, otherwise
    /// one that would carry the name `comm`.
    fn claim(&mut self, parent: Option<u32>, comm: &str) -> Option<Expected> {
        let at = match parent {
            Some(parent) => self
                .expected
                .iter()
                .position(|e| e.parent == parent && e.comm == comm)
                .or_else(|| self.expected.iter().position(|e| e.parent == parent)),
            None => self.expected.iter().position(|e| e.comm == comm),
        }?;
        self.expected.remove(at)
    }

    fn exec(&mut self, ts: u64, pid: u32, path: String, info: Option<ProcInfo>, out: &mut Vec<Event>) {
        let info = info.unwrap_or_default();
        // The process table is read a moment after the report, and the
        // process can have moved on to its next program by then (`env` to
        // `node`, a script to its interpreter). Arguments are only believed
        // when they are for the program reported.
        let is_it = self.is_running(&info, &path);
        let argv = match self.first.take() {
            Some(command) => command,
            None if is_it && !info.args.is_empty() => info.args,
            None => vec![path.clone()],
        };
        // Remember the program by the name the kernel has for it, which is
        // what later lookups return. It is not always the file name: a
        // program started through a symlink keeps the name of its target.
        let name = if is_it { comm_of(&info.exe) } else { comm_of(&path) };
        self.running.insert(pid, name);
        let what = What::Exec { ppid: info.ppid, uid: self.uid, exe: path, argv, cwd: info.cwd, existing: false };
        out.push(Event { ts, pid, what });
    }

    /// Does the process table show the process running the program at
    /// `path`? The kernel names a process after the file it really runs, so
    /// a program started through a symlink has to be compared by its target.
    fn is_running(&mut self, info: &ProcInfo, path: &str) -> bool {
        !info.exe.is_empty() && (same_program(&info.exe, path) || same_program(&info.exe, &self.table.resolve(path)))
    }

    /// A first report from a pid nobody has seen: say where it came from.
    fn introduce(&mut self, ts: u64, pid: u32, comm: &str, info: Option<&ProcInfo>, out: &mut Vec<Event>) {
        let certain = info.map(|i| i.ppid).filter(|p| self.running.contains_key(p));
        let claimed = self.claim(certain, comm);
        let Some(ppid) = certain.or(claimed.as_ref().map(|e| e.parent)) else {
            self.running.insert(pid, comm.to_string());
            return;
        };
        out.push(Event { ts, pid, what: What::Fork { ppid } });
        let inherited = self.running.get(&ppid).cloned().unwrap_or_else(|| comm.to_string());
        self.running.insert(pid, inherited);
        // A spawned child starts life running its program; the report of
        // that came under the parent's pid and was held for this moment.
        if let Some(path) = claimed.and_then(|e| e.spawned) {
            let info = self.table.info(pid);
            self.exec(ts, pid, path, info, out);
        }
    }

    /// An exec report under a pid already running `prev`. Is it that
    /// process replacing itself, or a child it spawned?
    fn is_spawn(&mut self, pid: u32, prev: &str, path: &str, info: Option<&ProcInfo>) -> bool {
        // Gone already: nothing to go on. A parent usually outlives its
        // children, so a vanished process more likely replaced itself.
        let Some(info) = info else {
            return false;
        };
        if self.is_running(info, path) && !same_program(prev, path) {
            return false; // it is running the reported program
        }
        if !same_program(&info.exe, prev) {
            return false; // it has moved on twice; replaced itself both times
        }
        // Still running what it ran before. Either it spawned a child, or
        // it replaced itself with a script whose interpreter happens to be
        // the same program. A new child decides it.
        if self.table.children(pid).iter().any(|c| !self.running.contains_key(c)) {
            return true;
        }
        !self.table.is_script(path)
    }

    pub fn feed(&mut self, report: Report, ts: u64) -> Vec<Event> {
        let Report { comm, pid, op } = report;
        let mut out = Vec::new();
        let known = self.running.contains_key(&pid);

        match op {
            Op::Fork => {
                if !known {
                    self.introduce(ts, pid, &comm, None, &mut out);
                }
                self.expect(Expected { parent: pid, comm, spawned: None });
            }
            Op::Exec { path } => {
                let info = self.table.info(pid);
                let prev = self.running.get(&pid).cloned();
                match prev {
                    Some(prev) if self.first.is_none() && self.is_spawn(pid, &prev, &path, info.as_ref()) => {
                        // Find the child now if it is still there; otherwise
                        // it is introduced by its own first report.
                        let child = self.table.children(pid).into_iter().find(|c| !self.running.contains_key(c));
                        match child {
                            Some(child) => {
                                out.push(Event { ts, pid: child, what: What::Fork { ppid: pid } });
                                let info = self.table.info(child);
                                self.exec(ts, child, path, info, &mut out);
                            }
                            None => self.expect(Expected { parent: pid, comm: comm_of(&path), spawned: Some(path) }),
                        }
                    }
                    _ => {
                        if !known {
                            self.introduce(ts, pid, &comm, info.as_ref(), &mut out);
                        }
                        self.exec(ts, pid, path, info, &mut out);
                    }
                }
            }
            Op::Read { .. } | Op::Write { .. } | Op::Unix { .. } | Op::Port { .. } => {
                if !known {
                    self.introduce(ts, pid, &comm, None, &mut out);
                }
                let what = match op {
                    Op::Read { path } => {
                        // Reading a directory is listing it.
                        let dir = self.table.is_dir(&path);
                        What::Open { path, write: false, dir }
                    }
                    Op::Write { path } => What::Open { path, write: true, dir: false },
                    Op::Unix { path } => What::Connect { peer: Peer::Unix { path }, name: None },
                    Op::Port { port } => What::Connect { peer: Peer::Port { port }, name: None },
                    Op::Fork | Op::Exec { .. } => return out,
                };
                out.push(Event { ts, pid, what });
            }
        }
        out
    }

    /// The stream has ended. Spawned children that never reported anything
    /// themselves were real all the same: report them, under stand-in pids
    /// since their own were never seen.
    pub fn finish(&mut self, ts: u64) -> Vec<Event> {
        let mut out = Vec::new();
        for e in std::mem::take(&mut self.expected) {
            let Some(path) = e.spawned else {
                continue;
            };
            let pid = self.next_unseen;
            self.next_unseen += 1;
            out.push(Event { ts, pid, what: What::Fork { ppid: e.parent } });
            self.exec(ts, pid, path, None, &mut out);
        }
        out
    }
}

