    #[test]
    fn parses_reports() {
        let p = |m: &str| parse_report(m);
        assert_eq!(
            p("Sandbox: sandbox-exec(52485) allow process-exec* /bin/sh\ncw1"),
            Some(rep("sandbox-exec", 52485, Op::Exec { path: "/bin/sh".into() }))
        );
        assert_eq!(p("Sandbox: bash(52485) allow process-fork\ncw1"), Some(rep("bash", 52485, Op::Fork)));
        assert_eq!(
            p("Sandbox: cat(7) allow file-read-data /Users/sam/My Files/.env\ncw1"),
            Some(rep("cat", 7, Op::Read { path: "/Users/sam/My Files/.env".into() }))
        );
        assert_eq!(
            p("Sandbox: mv(7) allow file-write-unlink /private/tmp/x/.env"),
            Some(rep("mv", 7, Op::Write { path: "/tmp/x/.env".into() }))
        );
        assert_eq!(
            p("Sandbox: nc(9) allow network-outbound remote:*:443\ncw1"),
            Some(rep("nc", 9, Op::Port { port: 443 }))
        );
        assert_eq!(
            p("Sandbox: curl(9) allow network-outbound /private/var/run/mDNSResponder\ncw1"),
            Some(rep("curl", 9, Op::Unix { path: "/var/run/mDNSResponder".into() }))
        );
        // A process name with parentheses and spaces in it.
        assert_eq!(
            p("Sandbox: Google Chrome He (1)(31) allow process-fork"),
            Some(rep("Google Chrome He (1)", 31, Op::Fork))
        );
    }

